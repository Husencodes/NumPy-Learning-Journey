# Importing the NumPy library
import numpy as np

# Generating numbers from 1 to 10 (11 is excluded)
a = np.arange(1, 11)

# Generating 5 equally spaced values between 1 and 10
b = np.linspace(1, 10, 5)

# Displaying the arange array
print("Arange:", a)

# Displaying the linspace array
print("Linspace:", b)
