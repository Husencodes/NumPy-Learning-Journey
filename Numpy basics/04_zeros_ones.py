# Importing the NumPy library
import numpy as np

# Creating a 2D array with 2 rows and 3 columns filled with zeros
zeros = np.zeros((2, 3))

# Creating a 2D array with 2 rows and 3 columns filled with ones
ones = np.ones((2, 3))

# Displaying the Zero Array heading
print("Zeros Array:")

# Printing the zero array
print(zeros)

# Displaying the One Array heading
print("Ones Array:")

# Printing the one array
print(ones)
