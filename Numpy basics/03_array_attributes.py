
# Importing the NumPy library
import numpy as np

# Creating a 2D NumPy array with 2 rows and 3 columns
arr = np.array([[10,20,30],
                [40,50,60]])

# Displaying the number of dimensions
print("Dimensions:-", arr.ndim)

# Displaying the shape (rows and columns)
print("Shape:-", arr.shape)

# Displaying the total number of elements
print("Size:-", arr.size)

# Displaying the data type of array elements
print("Data type:-", arr.dtype)
