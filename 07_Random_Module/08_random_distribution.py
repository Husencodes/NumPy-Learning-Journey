import numpy as np

# Uniform distribution
uniform = np.random.uniform(1, 10, 5)

# Normal distribution
normal = np.random.normal(0, 1, 5)

# Binomial distribution
binomial = np.random.binomial(10, 0.5, 5)

print("Uniform:", uniform)
print("Normal:", normal)
print("Binomial:", binomial)